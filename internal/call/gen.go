//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen.go. DO NOT EDIT.\n\n")
	b.WriteString("//go:build ((amd64 || arm64) && (darwin || freebsd || linux || netbsd || windows)) || (386 && (linux || windows)) || (arm && linux)\n\npackage call\n")
	for n := 0; n <= maxArgs; n++ {
		var params []string
		for i := range n {
			params = append(params, fmt.Sprintf("a%d", i))
		}
		decl, d := "fn uintptr, desc uint64", "[2]uint64{desc}"
		if n > 16 {
			decl, d = "fn uintptr, desc, desc2 uint64", "[2]uint64{desc, desc2}"
		}
		slice := "nil"
		if n > 0 {
			decl += ", " + strings.Join(params, ", ") + " uintptr"
			slice = "[]uintptr{" + strings.Join(params, ", ") + "}"
		}
		for _, v := range []struct {
			name, doc, typ, res string
			fret                bool
		}{
			{"Call", "the integer result", "uintptr", "r, _, _ := ret", false},
			{"WCall", "the 64-bit integer result", "uint64", "_, _, r := ret", false},
			{"FCall", "the bits of the floating-point result", "uint64", "_, r, _ := ret", true},
		} {
			fmt.Fprintf(&b, "\n// %s%d calls fn and returns %s.\n//\n//go:uintptrescapes\n", v.name, n, v.doc)
			fmt.Fprintf(&b, "func %s%d(%s) %s {\n\t%s(do(fn, %s, %s, %v))\n\treturn r\n}\n", v.name, n, decl, v.typ, v.res, d, slice, v.fret)
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("args.go", src, 0o644); err != nil {
		panic(err)
	}
}

const maxArgs = 32
