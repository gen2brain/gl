var docLicense string

func writeGo(path string, b *bytes.Buffer) error {
	src, err := format.Source(b.Bytes())
	if err != nil {
		os.WriteFile(path+".broken", b.Bytes(), 0o644)
		return fmt.Errorf("%s: %w", path, err)
	}
	return os.WriteFile(path, src, 0o644)
}

func (p *Package) generate(root string) error {
	dir := filepath.Join(root, p.Dir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, f := range []func(string) error{p.emitPackage, p.emitFuncs, p.emitConversions, p.emitDebug} {
		if err := f(dir); err != nil {
			return err
		}
	}
	if p.WebGL {
		return p.emitWebGL(dir, p.webglDir, p.idl)
	}
	return nil
}

func (p *Package) emitPackage(dir string) error {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString(docLicense)
	fmt.Fprintf(&b, "// Package %s implements Go bindings to OpenGL", p.Name)
	if p.API == "gles2" {
		b.WriteString(" ES")
	}
	b.WriteString(".\npackage " + p.Name + "\n\nconst (\n")
	for _, e := range p.Enums {
		fmt.Fprintf(&b, "\t%s = %s\n", e.GoName, e.Value)
	}
	b.WriteString(")\n")
	return writeGo(filepath.Join(dir, "package.go"), &b)
}

func (p *Package) emitFuncs(dir string) error {
	var body bytes.Buffer

	body.WriteString("var (\n")
	for _, c := range p.Commands {
		fmt.Fprintf(&body, "\tgp%s uintptr\n", c.GoName)
	}
	body.WriteString(")\n\n")

	body.WriteString("var procs = [...]struct {\n\taddr     *uintptr\n\tname     string\n\trequired bool\n}{\n")
	for _, c := range p.Commands {
		fmt.Fprintf(&body, "\t{&gp%s, %q, %v},\n", c.GoName, c.Name, c.Required)
	}
	body.WriteString("}\n\n")

	body.WriteString("func boolToUintptr(b bool) uintptr {\n\tif b {\n\t\treturn 1\n\t}\n\treturn 0\n}\n")

	var wide, wide32 bytes.Buffer
	for _, c := range p.Commands {
		if !wideParams(c.Params) {
			if err := writeCommand(&body, c, false); err != nil {
				return err
			}
			continue
		}
		if err := writeCommand(&wide, c, false); err != nil {
			return err
		}
		if err := writeCommand(&wide32, c, true); err != nil {
			return err
		}
	}

	api := "procaddr.GL"
	if p.API == "gles2" {
		api = "procaddr.GLES"
	}
	fmt.Fprintf(&body, `
// Init loads the function pointers of the current context.
func Init() error {
	getProcAddr, err := procaddr.New(%s)
	if err != nil {
		return err
	}
	return InitWithProcAddrFunc(getProcAddr)
}

// InitWithProcAddrFunc loads the function pointers with getProcAddr.
func InitWithProcAddrFunc(getProcAddr func(name string) unsafe.Pointer) error {
	var err error
	for _, p := range procs {
		*p.addr = uintptr(getProcAddr(p.name))
		if *p.addr == 0 && p.required && err == nil {
			err = errors.New(p.name)
		}
	}
	return err
}
`, api)

	if err := writeGo(filepath.Join(dir, "funcs.go"), goFile(p.Name, "!js", body.Bytes(), "errors")); err != nil {
		return err
	}
	for _, f := range []string{"funcs_wide.go", "funcs_wide32.go"} {
		os.Remove(filepath.Join(dir, f))
	}
	if wide.Len() == 0 {
		return nil
	}
	if err := writeGo(filepath.Join(dir, "funcs_wide.go"), goFile(p.Name, "!js && !386 && !arm", wide.Bytes())); err != nil {
		return err
	}
	return writeGo(filepath.Join(dir, "funcs_wide32.go"), goFile(p.Name, "!js && (386 || arm)", wide32.Bytes()))
}

func comment(c *Command, params []Param) string {
	var lines []string
	if c.Doc != "" {
		lines = append(lines, "// "+c.Doc)
	}
	for _, p := range params {
		if t := p.Type; t.GoType() == "unsafe.Pointer" && t.Name != "void" && t.Name != "GLvoid" {
			lines = append(lines, fmt.Sprintf("// Parameter %s has type %s.", p.Name, cTypeName(t)))
		}
	}
	if r := c.Return; r.GoType() == "unsafe.Pointer" && r.Name != "void" && r.Name != "GLvoid" {
		lines = append(lines, fmt.Sprintf("// Return value has type %s.", cTypeName(r)))
	}
	if len(lines) == 0 {
		return ""
	}
	return strings.Join(lines, "\n") + "\n"
}

func cTypeName(t Type) string {
	return strings.Repeat("*", t.Pointers) + t.Name
}

func writeFunc(b *bytes.Buffer, c *Command, name string, params []Param, doc bool, split bool) error {
	var decl, args []string
	for _, p := range params {
		decl = append(decl, goName(p.Name)+" "+p.Type.GoType())
		args = append(args, argExprs(p, split)...)
	}
	d, err := descriptor(params, len(args))
	if err != nil {
		return err
	}
	ret := ""
	if !c.Return.IsVoid() {
		ret = " " + c.Return.GoType()
	}
	b.WriteString("\n")
	if doc {
		b.WriteString(comment(c, params))
	} else {
		b.WriteString(comment(&Command{Return: c.Return}, params))
	}
	fmt.Fprintf(b, "func %s(%s)%s {\n", name, strings.Join(decl, ", "), ret)

	fn := "Call"
	switch c.Return.GoType() {
	case "float32", "float64":
		fn = "FCall"
	case "int64", "uint64":
		fn = "WCall"
	}
	callArgs := fmt.Sprintf("gp%s, %s", c.GoName, d)
	if len(args) > 0 {
		callArgs += ", " + strings.Join(args, ", ")
	}
	invoke := fmt.Sprintf("call.%s%d(%s)", fn, len(args), callArgs)

	switch gt := c.Return.GoType(); {
	case c.Return.IsVoid():
		b.WriteString("\t" + invoke + "\n")
	case gt == "bool":
		b.WriteString("\treturn uint8(" + invoke + ") != 0\n")
	case gt == "float32":
		b.WriteString("\treturn math.Float32frombits(call.F32Bits(" + invoke + "))\n")
	case gt == "float64":
		b.WriteString("\treturn math.Float64frombits(" + invoke + ")\n")
	case gt == "unsafe.Pointer":
		b.WriteString("\tr := " + invoke + "\n\treturn *(*unsafe.Pointer)(unsafe.Pointer(&r))\n")
	case strings.HasPrefix(gt, "*"):
		b.WriteString("\tr := " + invoke + "\n\treturn *(*" + gt + ")(unsafe.Pointer(&r))\n")
	default:
		b.WriteString("\treturn " + gt + "(" + invoke + ")\n")
	}
	b.WriteString("}\n")
	return nil
}

func writeCommand(b *bytes.Buffer, c *Command, split bool) error {
	if err := writeFunc(b, c, c.GoName, c.Params, true, split); err != nil {
		return fmt.Errorf("%s: %w", c.Name, err)
	}
	for _, o := range c.Overloads {
		if err := writeFunc(b, c, o.GoName, o.Params, false, split); err != nil {
			return fmt.Errorf("%s: %w", o.GoName, err)
		}
	}
	return nil
}

func goFile(name, tags string, body []byte, extra ...string) *bytes.Buffer {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("//go:build " + tags + "\n\npackage " + name + "\n\nimport (\n")
	for _, imp := range extra {
		b.WriteString("\t\"" + imp + "\"\n")
	}
	if bytes.Contains(body, []byte("math.")) {
		b.WriteString("\t\"math\"\n")
	}
	if bytes.Contains(body, []byte("unsafe.")) {
		b.WriteString("\t\"unsafe\"\n")
	}
	b.WriteString("\n\t\"github.com/gen2brain/gl/internal/call\"\n")
	if bytes.Contains(body, []byte("procaddr.")) {
		b.WriteString("\t\"github.com/gen2brain/gl/internal/procaddr\"\n")
	}
	b.WriteString(")\n\n")
	b.Write(body)
	return &b
}

func (p *Package) emitConversions(dir string) error {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package " + p.Name + conversions)
	return writeGo(filepath.Join(dir, "conversions.go"), &b)
}

func (p *Package) hasDebugProc() bool {
	for _, c := range p.Commands {
		for _, prm := range c.Params {
			if prm.Type.IsDebugProc() {
				return true
			}
		}
	}
	return false
}

func (p *Package) emitDebug(dir string) error {
	if !p.hasDebugProc() {
		return nil
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package " + p.Name + debugType)
	if err := writeGo(filepath.Join(dir, "debug.go"), &b); err != nil {
		return err
	}
	b.Reset()
	b.WriteString(header)
	b.WriteString("//go:build !js\n\npackage " + p.Name + debugNative)
	return writeGo(filepath.Join(dir, "debug_native.go"), &b)
}

const conversions = `

import (
	"fmt"
	"reflect"
	"runtime"
	"strings"
	"unsafe"
)

// Ptr returns the address of a slice or of a pointer to a scalar.
func Ptr(data any) unsafe.Pointer {
	if data == nil {
		return unsafe.Pointer(nil)
	}
	var addr unsafe.Pointer
	v := reflect.ValueOf(data)
	switch v.Type().Kind() {
	case reflect.Pointer:
		e := v.Elem()
		switch e.Kind() {
		case
			reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
			reflect.Float32, reflect.Float64:
			addr = v.UnsafePointer()
		default:
			panic(fmt.Errorf("unsupported pointer to type %s; must be a slice or pointer to a singular scalar value or the first element of an array or slice", e.Kind()))
		}
	case reflect.Uintptr:
		u := data.(uintptr)
		addr = *(*unsafe.Pointer)(unsafe.Pointer(&u))
	case reflect.Slice:
		addr = v.Index(0).Addr().UnsafePointer()
	default:
		panic(fmt.Errorf("unsupported type %s; must be a slice or pointer to a singular scalar value or the first element of an array or slice", v.Type()))
	}
	return addr
}

// PtrOffset returns offset as a pointer.
//
// Deprecated: Use the WithOffset functions, e.g. VertexAttribPointerWithOffset.
func PtrOffset(offset int) unsafe.Pointer {
	u := uintptr(offset)
	return *(*unsafe.Pointer)(unsafe.Pointer(&u))
}

// Str returns the address of the null-terminated string str.
func Str(str string) *uint8 {
	if !strings.HasSuffix(str, "\x00") {
		panic("str argument missing null terminator: " + str)
	}
	return unsafe.StringData(str)
}

// GoStr returns the Go string of the null-terminated cstr.
func GoStr(cstr *uint8) string {
	if cstr == nil {
		return ""
	}
	n := 0
	for *(*uint8)(unsafe.Add(unsafe.Pointer(cstr), n)) != 0 {
		n++
	}
	return string(unsafe.Slice(cstr, n))
}

// Strs returns the C array of strs, valid until free is called.
func Strs(strs ...string) (cstrs **uint8, free func()) {
	if len(strs) == 0 {
		panic("Strs: expected at least 1 string")
	}
	n := 0
	for i := range strs {
		n += len(strs[i])
	}
	data := make([]byte, max(n, 1))
	css := make([]*uint8, len(strs))
	offset := 0
	for i := range strs {
		copy(data[offset:], strs[i])
		css[i] = &data[offset]
		offset += len(strs[i])
	}
	var pinner runtime.Pinner
	pinner.Pin(&data[0])
	pinner.Pin(&css[0])
	return &css[0], pinner.Unpin
}
`

const debugType = `

import "unsafe"

// DebugProc is the debug message callback.
type DebugProc func(
	source uint32,
	gltype uint32,
	id uint32,
	severity uint32,
	length int32,
	message string,
	userParam unsafe.Pointer)
`

const debugNative = `

import (
	"sync"
	"unsafe"

	"github.com/gen2brain/gl/internal/debugcb"
)

var (
	userDebugCallback DebugProc
	debugCallbackOnce sync.Once
	debugCallbackPtr  uintptr
)

func debugCallback(callback DebugProc) uintptr {
	userDebugCallback = callback
	if callback == nil {
		return 0
	}
	debugCallbackOnce.Do(func() {
		debugCallbackPtr = debugcb.New(func(source, gltype, id, severity uint32, length int32, message *uint8, userParam unsafe.Pointer) {
			if cb := userDebugCallback; cb != nil {
				cb(source, gltype, id, severity, length, GoStr(message), userParam)
			}
		})
	})
	return debugCallbackPtr
}
`
